#[cfg(target_feature = "bmi2")]
use std::arch::x86_64::_pext_u64;

use crate::repr::bitboard::BB;

#[cfg(target_feature = "bmi2")]
pub fn pext_index(occupancy: BB, mask: BB) -> usize {
    unsafe { _pext_u64(occupancy.0, mask.0) as usize }
}

